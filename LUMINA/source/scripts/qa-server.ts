import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../server/index';
import { makePlan } from '../shared/scenes';
import { serializeIES, samplePhotometry } from '../shared/photometry';
import type { Vec3 } from '../shared/types';
const root=await fs.mkdtemp(path.join(os.tmpdir(),'lumina-browser-qa-'));
const {app,store}=await createApp(root);
const plan=makePlan('indoor');plan.id='qa-30';plan.name='30 灯具验证场景';
for(let i=0;i<13;i++)plan.fixtures.push({...structuredClone(plan.fixtures[0]),id:`qa-copy-${i}`,slotId:undefined,position:[-6+(i%5)*2.5,3.8,-4+Math.floor(i/5)*3] as Vec3});
plan.presets=plan.presets.map(pre=>({...pre,values:plan.fixtures.map(f=>({id:f.id,level:pre.id==='off'?0:pre.id==='warm'?60:100,cct:f.cct}))}));
await store.savePlan(plan);
await fs.writeFile(path.join(root,'qa-photometry.ies'),serializeIES(samplePhotometry('筒灯',1000,12)));
await app.listen({host:'127.0.0.1',port:3141});console.log(JSON.stringify({url:'http://127.0.0.1:3141/',data:root,ies:path.join(root,'qa-photometry.ies'),step:path.resolve('node_modules/occt-import-js/test/testfiles/cube-10x10mm/Cube 10x10.stp')}));
process.on('SIGTERM',async()=>{await app.close();await fs.rm(root,{recursive:true,force:true});process.exit(0);});
process.on('SIGINT',async()=>{await app.close();await fs.rm(root,{recursive:true,force:true});process.exit(0);});
