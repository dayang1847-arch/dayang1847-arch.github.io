import assert from 'node:assert/strict';
import { calibrateContourRecord, rotateContourRecord, selectCalibratedContours } from '../contour-session.mjs';

const raw={contourId:'lamp',sourceName:'Lamp.pdf',pointsMm:[[0,0],[20,0],[30,40],[0,0]],widthMm:30,heightMm:40,scale:1,calibrated:false};
const records=new Map([['lamp',raw]]);
assert.throws(()=>selectCalibratedContours(records,[{contourId:'lamp'}]),/校准/);
const first=calibrateContourRecord(raw,[0,0],[0,40],80);
assert.equal(first.widthMm,60);
assert.equal(first.heightMm,80);
assert.equal(first.scale,2);
assert.equal(first.measurementMm,80);
assert.deepEqual(raw.pointsMm[1],[20,0]);
assert.deepEqual(first.pointsMm[1],[40,0]);
const second=calibrateContourRecord(first,[0,0],[60,80],75);
assert.equal(second.widthMm,45);
assert.equal(second.heightMm,60);
assert.equal(second.measurementMm,75);
assert.equal(second.scale,1.5);
const rotated=rotateContourRecord({...second,basePoints:raw.pointsMm,baseWidth:30,baseHeight:40});
assert.equal(rotated.widthMm,60);
assert.equal(rotated.heightMm,45);
assert.equal(rotated.baseWidth,40);
assert.equal(rotated.baseHeight,30);
assert.equal(Math.hypot(rotated.calibration.point2[0]-rotated.calibration.point1[0],rotated.calibration.point2[1]-rotated.calibration.point1[1]),75);
records.set('lamp',second);
assert.equal(selectCalibratedContours(records,[{contourId:'lamp',label:'T70'}])[0].label,'T70');
assert.throws(()=>selectCalibratedContours(records,[{contourId:'lamp'},{contourId:'lamp'}]),/重复/);
assert.throws(()=>selectCalibratedContours(records,[{contourId:'deleted'}]),/清空/);
assert.throws(()=>calibrateContourRecord(raw,[0,0],[0,0],80),/过近/);
assert.throws(()=>calibrateContourRecord(raw,[0,0],[31,40],80),/超出/);
assert.throws(()=>calibrateContourRecord(raw,[0,0],[0,40],0),/大于/);
assert.throws(()=>calibrateContourRecord(raw,[NaN,0],[0,40],80),/有效/);
console.log('Contour calibration and export guard tests passed.');
